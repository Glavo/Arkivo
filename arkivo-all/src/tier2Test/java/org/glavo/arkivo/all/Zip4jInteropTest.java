    /// Reads Zip4j-generated split and ordinary archives and validates each body against its source file.
    @ParameterizedTest
    @MethodSource("generatedConfigurations")
    void readsGeneratedArchives(CompressionMethod method, ZipEncryption encryption, boolean split,
                               @TempDir Path directory) throws IOException {
        Path archive = directory.resolve("generated.zip");
        var parameters = new ZipParameters();
        parameters.setCompressionMethod(method);
        parameters.setEncryptFiles(encryption != ZipEncryption.NONE);
        parameters.setEncryptionMethod(encryption == ZipEncryption.NONE ? EncryptionMethod.NONE
                : encryption == ZipEncryption.ZIP_CRYPTO ? EncryptionMethod.ZIP_STANDARD : EncryptionMethod.AES);
        parameters.setAesKeyStrength(switch (encryption) {
            case WINZIP_AES_128 -> AesKeyStrength.KEY_STRENGTH_128;
            case WINZIP_AES_192 -> AesKeyStrength.KEY_STRENGTH_192;
            default -> AesKeyStrength.KEY_STRENGTH_256;
        });
        var names = List.of("file_PDF_1MB.pdf", "sample_text1.txt", "zero_byte_file.txt");
        try (var reference = new ZipFile(archive.toFile(), PASSWORD.toCharArray())) {
            reference.createSplitZipFile(names.stream().map(name -> content(name).toFile()).toList(),
                    parameters, split, split ? 65536 : -1);
        }
        if (split) {
            assertTrue(Files.isRegularFile(directory.resolve("generated.z01")));
        }
        Map<String, String> passwords = Map.of("*", PASSWORD);
        assertReadable(archive, StandardCharsets.UTF_8, passwords, split);
        try (var fileSystem = ZipArkivoFileSystem.open(archive, readOptions(StandardCharsets.UTF_8, passwords))) {
            for (String name : names) {
                assertArrayEquals(Files.readAllBytes(content(name)), Files.readAllBytes(fileSystem.getPath("/" + name)));
            }
        }
    }

