    /// Resolves archive-local links without creating host symlinks and retains their raw streaming bodies.
    @Test
    void readsSymbolicLinks() throws IOException {
        Path archive = archive("zipWithLinkToDirAndFolder.zip");
        Map<String, String> targets = Map.of("b", "a", "d", "c");
        try (var reference = new ZipFile(archive.toFile());
             var fileSystem = ZipArkivoFileSystem.open(archive)) {
            assertEquals(5, reference.getFileHeaders().size());
            for (var link : targets.entrySet()) {
                try (var input = reference.getInputStream(reference.getFileHeader(link.getKey()))) {
                    assertArrayEquals(link.getValue().getBytes(StandardCharsets.UTF_8), input.readAllBytes());
                }
                Path path = fileSystem.getPath("/" + link.getKey());
                assertTrue(Files.isSymbolicLink(path));
                assertEquals(link.getValue(), Files.readSymbolicLink(path).toString());
            }
            assertTrue(Files.isDirectory(fileSystem.getPath("/b")));
            assertTrue(Files.isRegularFile(fileSystem.getPath("/d")));
            assertArrayEquals(new byte[0], Files.readAllBytes(fileSystem.getPath("/d")));
        }
        try (var reader = ZipArkivoStreamingReader.open(archive)) {
            int entries = 0;
            var links = new HashSet<String>();
            while (reader.next()) {
                entries++;
                String name = reader.readAttributes().path();
                if (targets.containsKey(name)) {
                    links.add(name);
                    // Unix file types live in the central directory, not in these local headers.
                    assertFalse(reader.readAttributes().isSymbolicLink());
                    try (var input = reader.openInputStream()) {
                        assertArrayEquals(targets.get(name).getBytes(StandardCharsets.UTF_8), input.readAllBytes());
                    }
                }
            }
            assertEquals(5, entries);
            assertEquals(targets.keySet(), links);
        }
    }

